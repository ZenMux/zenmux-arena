export type VendorIconKey = typeof VENDOR_ICON_KEYS[number];
const iconKeys: ReadonlySet<string> = new Set(VENDOR_ICON_KEYS);

export function resolveVendorIconKey(raw: string | null | undefined): VendorIconKey | null {
  if (!raw) return null;
  let key = raw.trim().toLowerCase();
  if (key.startsWith("other:")) key = key.slice("other:".length);
  if (key.startsWith("/model-logo/")) key = key.slice("/model-logo/".length);
  if (key.startsWith("/maker-logo/")) key = key.slice("/maker-logo/".length);
  key = key
    .replace(/\.(svg|png)$/i, "")
    .replace(/_(color-dark|color-light|color|dark|light)$/i, "");
  return iconKeys.has(key) ? key as VendorIconKey : null;
}

export function hasVendorIcon(vendorOrKey: string | null | undefined): boolean {
  return resolveVendorIconKey(vendorOrKey) !== null;
}
